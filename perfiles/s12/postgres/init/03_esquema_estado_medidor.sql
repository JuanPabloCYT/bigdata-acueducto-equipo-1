-- veces contra la API simulada. stg_estado_medidor tiene 90 medidores (la segunda
-- corrida actualizo las filas sin duplicarlas) y bitacora_ingesta_api conserva los
-- intentos de ambas corridas.
-- Tablas del estado de medidores que llena el conector de la API:
--   stg_estado_medidor    estado vigente de cada medidor. Se escribe con UPSERT por
--                         meter_id: repetir una corrida actualiza filas, no las duplica.
--   bitacora_ingesta_api  auditoria de cada intento contra la API (corrida, equipo,
--                         pagina, intento, codigo, duracion y resultado). Solo se
--                         insertan filas: nunca se actualiza ni se deduplica, por eso
--                         crece con cada corrida. id es un consecutivo de insercion.
-- Este archivo se ejecuta automaticamente la primera vez que arranca el contenedor,
-- despues de los dos anteriores (orden alfabetico).

