    meter_id VARCHAR PRIMARY KEY,
    sector VARCHAR,
    saldo DOUBLE PRECISION,
    estado_servicio VARCHAR,
    actualizado_en TIMESTAMP
);

CREATE TABLE bitacora_ingesta_api (
    id BIGSERIAL PRIMARY KEY,
    corrida_id VARCHAR NOT NULL,
    equipo VARCHAR,
    pagina INTEGER NOT NULL,
    intento INTEGER NOT NULL,
    codigo_http INTEGER,
    duracion_ms DOUBLE PRECISION,
    resultado VARCHAR NOT NULL,
    timestamp_intento TIMESTAMP NOT NULL DEFAULT now()
);

